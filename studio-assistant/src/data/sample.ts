let photoSeq = 0
function photos(kinds: PhotoKind[], names: string[], offset = 0): Photo[] {
  return kinds.map((kind, i) => {
    const p = PALETTES[(i + offset) % PALETTES.length]
    photoSeq++
    return {
      id: `ph${photoSeq}`,
      kind,
      ...p,
      name: names[i % names.length] + ` — ${String(i + 1).padStart(2, '0')}`,
      favourite: false,
      comments: [],
    }
  })
}

function comment(who: string, text: string, at: number, fromClient = true): Comment {
  return { id: `c${Math.random().toString(36).slice(2, 8)}`, who, text, at, fromClient }
}

