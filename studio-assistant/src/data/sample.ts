function ago(days: number, hour = 9, min = 0): number {
  const d = new Date()
  d.setDate(d.getDate() - days)
  d.setHours(hour, min, 0, 0)
  return d.getTime()
}

function hoursAgo(h: number): number {
  return Date.now() - h * 3600_000
}

